for t in types_and_names:
	c.write(read.replace("{easy}", t[0]).replace("{real}", t[1]).replace("{default}", t[2]))

c.write("// Writes\n")
for t in types_and_names:
	c.write(write.replace("{easy}", t[0]).replace("{real}", t[1]).replace("{default}", t[2]))

h.write("// Auto-generated by generate_serialise_for_types.py\n")
